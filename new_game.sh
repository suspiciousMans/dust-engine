#!/usr/bin/env bash
# Scaffolds a new game by copying games/sandbox as a template, renaming its
# crate, and registering it in the workspace. POSIX/bash equivalent of
# new_game.ps1.
#
# Usage: ./new_game.sh <name> [--no-build]
#   <name>       lowercase letters, digits, underscores; must start with a letter
#   --no-build   skip the final `cargo build -p <name>` verification step
set -euo pipefail

usage() {
    echo "Usage: $0 <name> [--no-build]" >&2
    exit 2
}

name=""
build=1
for arg in "$@"; do
    case "$arg" in
        --no-build) build=0 ;;
        -h|--help) usage ;;
        -*) echo "error: unknown option '$arg'" >&2; usage ;;
        *)
            [ -z "$name" ] || usage
            name="$arg"
            ;;
    esac
done
[ -n "$name" ] || usage

root="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source_dir="$root/games/sandbox"
dest_dir="$root/games/$name"

if [[ ! "$name" =~ ^[a-z][a-z0-9_]*$ ]]; then
    echo "error: Name must be a valid Cargo package name: lowercase letters, digits, underscores, starting with a letter (got '$name')" >&2
    exit 1
fi

if [ -e "$dest_dir" ]; then
    echo "error: games/$name already exists" >&2
    exit 1
fi

if [ ! -d "$source_dir" ]; then
    echo "error: template games/sandbox not found" >&2
    exit 1
fi

# Directories bootstrap-generated by Sandbox::init on first run (profiles,
# levels, rigs, classes, sfx, music) or by gameplay (saves) - excluded so
# the new game gets its own fresh first-run experience via the same
# default_level()/default_demo_profiles()/etc. functions it inherits in
# src/main.rs, rather than copying the sandbox's already-played-with state.
exclude_dirs=(profiles levels rigs classes sfx music saves)

echo "Creating '$name' from the sandbox template..."
mkdir -p "$dest_dir"
shopt -s dotglob nullglob
for entry in "$source_dir"/*; do
    base="$(basename "$entry")"
    skip=0
    for ex in "${exclude_dirs[@]}"; do
        [ "$base" = "$ex" ] && skip=1
    done
    [ "$skip" -eq 1 ] || cp -R "$entry" "$dest_dir/"
done
shopt -u dotglob nullglob

# Rename the crate/package.
sed -i.bak "s/name = \"sandbox\"/name = \"$name\"/" "$dest_dir/Cargo.toml"

# Rename the window title / fatal-error dialog title in the copied source.
sed -i.bak \
    -e "s/Jame Engine Sandbox - Error/Jame Engine $name - Error/g" \
    -e "s/Jame Engine Sandbox/Jame Engine $name/g" \
    "$dest_dir/src/main.rs"
rm -f "$dest_dir/Cargo.toml.bak" "$dest_dir/src/main.rs.bak"

# Register the new crate in the workspace (single-line `members = [...]`).
workspace_toml="$root/Cargo.toml"
member="\"games/$name\""
if ! grep -qF "$member" "$workspace_toml"; then
    if ! grep -qE '^members[[:space:]]*=.*\]' "$workspace_toml"; then
        echo "error: could not find a single-line 'members = [...]' in Cargo.toml; add $member by hand" >&2
        exit 1
    fi
    sed -i.bak -E "/^members[[:space:]]*=/ s|\]|, $member]|" "$workspace_toml"
    rm -f "$workspace_toml.bak"
fi

if [ "$build" -eq 1 ]; then
    echo "Building '$name' to verify the scaffold..."
    (cd "$root" && cargo build -p "$name")
fi

echo "Created games/$name - run it with: cargo run -p $name"
echo "Demo content (Cube 1/2/3, the humanoid rig, scripts, etc.) came along for the ride - replace it with your own as you go, same as editing the sandbox directly."
